#!/usr/bin/env bash
# Map locked Terraform outputs → harness env (1:1). No Terraform in this repo.
#
# Usage:
#   terraform -chdir=/path/to/infra output -json | ./scripts/export_env_from_tf.sh
#   ./scripts/export_env_from_tf.sh /path/to/infra
#   ./scripts/export_env_from_tf.sh /path/to/infra -json > tf-outputs.json
#
# Locked TF output → env
#   mysql_host_v4         MYSQL_HOST_V4
#   mysql_host_v7         MYSQL_HOST_V7
#   mysql_port            MYSQL_PORT
#   mysql_database        MYSQL_DATABASE
#   mysql_user            MYSQL_USER
#   mysql_secret_arn      MYSQL_SECRET_ARN
#   mysql_tls             MYSQL_TLS
#   aws_region            AWS_REGION
#   loadgen_instance_id   LOADGEN_INSTANCE_HINT
#
# Infra-only (not harness env; ignored if present):
#   loadgen_subnet_id, loadgen_sg_id, rds_sg_id
#
# Never emitted: mysql_password (use MYSQL_SECRET_ARN). No rds_endpoint_* aliases.
set -euo pipefail

usage() {
  sed -n '2,24p' "$0" | sed 's/^# \{0,1\}//'
}

if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
  usage
  exit 0
fi

json=""
if [[ -n "${1:-}" && -d "$1" ]]; then
  if [[ "${2:-}" == "-json" ]]; then
    terraform -chdir="$1" output -json
    exit 0
  fi
  json="$(terraform -chdir="$1" output -json)"
elif [[ ! -t 0 ]]; then
  json="$(cat)"
else
  usage >&2
  echo "error: pass a terraform dir or pipe terraform output -json" >&2
  exit 1
fi

python3 -c '
import json, sys

raw = sys.stdin.read()
if not raw.strip():
    sys.stderr.write("error: empty terraform output JSON\n")
    sys.exit(1)
data = json.loads(raw)

def val(name):
    item = data.get(name)
    if item is None:
        return None
    if isinstance(item, dict) and "value" in item:
        return item["value"]
    return item

# Locked 1:1 map. Do not add rds_endpoint_* aliases.
mapping = [
    ("mysql_host_v4", "MYSQL_HOST_V4"),
    ("mysql_host_v7", "MYSQL_HOST_V7"),
    ("mysql_port", "MYSQL_PORT"),
    ("mysql_database", "MYSQL_DATABASE"),
    ("mysql_user", "MYSQL_USER"),
    ("mysql_secret_arn", "MYSQL_SECRET_ARN"),
    ("mysql_tls", "MYSQL_TLS"),
    ("aws_region", "AWS_REGION"),
    ("loadgen_instance_id", "LOADGEN_INSTANCE_HINT"),
]
skip_infra = ("loadgen_subnet_id", "loadgen_sg_id", "rds_sg_id")
forbidden = ("mysql_password",)

print("# generated by scripts/export_env_from_tf.sh — locked TF output names")
print("# password: set MYSQL_SECRET_ARN only (no plaintext mysql_password)")
for src, dest in mapping:
    v = val(src)
    if v is None:
        print(f"# {dest}=   # terraform output {src} missing")
        continue
    if isinstance(v, bool):
        v = "true" if v else "false"
    print(f"{dest}={v}")

for name in skip_infra:
    if name in data:
        print(f"# skipped infra-only output {name}")
for name in forbidden:
    if name in data:
        print(f"# skipped {name} (never export plaintext password)")
for name in data:
    if name.startswith("rds_endpoint_"):
        print(f"# skipped {name} (no rds_endpoint_* aliases)")
' <<<"$json"
